"""
sentinel_ctf.workflows.writeup_gen
====================================
Auto-generate a markdown writeup from the challenge record and job history.
"""
from __future__ import annotations

import uuid
from datetime import datetime
from pathlib import Path

from sentinel_ctf.core.models import Challenge, Writeup, WriteupSection
from sentinel_ctf.core.database import list_jobs


_WRITEUP_TEMPLATE = """\
# {name}

**Category:** {category}  
**Platform:** {platform}  
**Event:** {event}  
**Points:** {points}  
**Flag:** `{flag}`  
**Solved:** {solved_at}

---

## Description

{description}

---

## Enumeration / Recon

{recon_section}

---

## Approach

{approach_section}

---

## Solution

{solution_section}

---

## Tools Used

{tools_list}

---

## Flag

```
{flag}
```

---

*Generated by Sentinel CTF Framework*
"""


def generate_writeup(challenge: Challenge) -> Writeup:
    """
    Build a Writeup model from the challenge and its job history.
    Does NOT write any files — call save_writeup() for that.
    """
    if not challenge.flag:
        raise ValueError(f"Challenge {challenge.name!r} has no flag set. Cannot generate writeup.")

    jobs = list_jobs(challenge.id)
    tools_used = list({j.tool for j in jobs})

    # Build recon section from job results
    recon_lines: list[str] = []
    for job in jobs:
        if job.result and job.result.stdout.strip():
            recon_lines.append(f"### {job.tool}\n\n```\n{job.result.stdout[:2000]}\n```\n")

    recon_section = "\n".join(recon_lines) if recon_lines else "(no automated recon recorded)"

    # Read notes from workspace for approach/solution
    approach_section = "(fill in from notes.md)"
    solution_section = "(fill in from notes.md)"
    if challenge.workspace_dir:
        notes_path = challenge.workspace_dir / "notes.md"
        if notes_path.exists():
            notes_text = notes_path.read_text(encoding="utf-8")
            # Extract sections
            approach_section = _extract_section(notes_text, "## Approach")
            solution_section = _extract_section(notes_text, "## Solution")

    sections = [
        WriteupSection(heading="Enumeration / Recon", content=recon_section),
        WriteupSection(heading="Approach", content=approach_section),
        WriteupSection(heading="Solution", content=solution_section),
    ]

    return Writeup(
        challenge_id=challenge.id,
        challenge_name=challenge.name,
        category=challenge.category,
        flag=challenge.flag,
        sections=sections,
        tools_used=tools_used,
    )


def save_writeup(writeup: Writeup, output_dir: Path) -> Path:
    """
    Render the writeup to a markdown file and save it.
    Returns the path of the saved file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    filename = f"{writeup.challenge_name.lower().replace(' ', '_')}_writeup.md"
    path = output_dir / filename

    tools_list = "\n".join(f"- {t}" for t in writeup.tools_used) or "- (none recorded)"
    recon = ""
    approach = ""
    solution = ""
    for s in writeup.sections:
        if "recon" in s.heading.lower():
            recon = s.content
        elif "approach" in s.heading.lower():
            approach = s.content
        elif "solution" in s.heading.lower():
            solution = s.content

    content = _WRITEUP_TEMPLATE.format(
        name=writeup.challenge_name,
        category=writeup.category.value,
        platform="",
        event="",
        points="",
        flag=writeup.flag,
        solved_at=writeup.created_at.strftime("%Y-%m-%d %H:%M UTC"),
        description="",
        recon_section=recon,
        approach_section=approach,
        solution_section=solution,
        tools_list=tools_list,
    )

    path.write_text(content, encoding="utf-8")
    return path


def _extract_section(text: str, heading: str) -> str:
    """Extract the content under a markdown heading until the next ## heading."""
    import re
    pattern = re.escape(heading) + r"\s*\n(.*?)(?=\n##|\Z)"
    m = re.search(pattern, text, re.DOTALL)
    if m:
        return m.group(1).strip()
    return ""
